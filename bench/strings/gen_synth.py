#!/usr/bin/env python3
"""Writes apps/synth.c: a page with SITES literal call sites (default 2,000), about 80% of them unique
strings, 3 to 30 bytes, one in ten non-ASCII; the strings come from one seeded xorshift32."""
import sys
SITES = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
seed = 0x5eed1234
def rnd():
    global seed
    seed ^= (seed << 13) & 0xffffffff; seed ^= seed >> 17; seed ^= (seed << 5) & 0xffffffff
    return seed
WORDS = ['alpha', 'bravo', 'charlie', 'delta', 'echo', 'foxtrot', 'golf', 'hotel', 'india', 'juliet', 'kilo',
         'lima', 'mike', 'november', 'oscar', 'papa', 'quebec', 'romeo', 'sierra', 'tango', 'uniform']
INTL = ['Привет', 'Grüße', 'こんにちは', 'café', 'naïve', 'Ελλάδα', '你好世界', 'Ünïcödé']
def text(i):
    n = 1 + rnd() % 4
    w = [WORDS[rnd() % len(WORDS)] for _ in range(n)]
    if rnd() % 10 == 0:
        w.insert(0, INTL[rnd() % len(INTL)])
    s = ' '.join(w) + ' %d' % i
    return s[:30]
def c(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
out = ['/* GENERATED by bench/strings/gen_synth.py: %d literal call sites. */' % SITES,
       '#include "cdom.h"', 'void cd_main(void) {', '  cd_at(CD_MOUNT, 0);', '  cd_open(CD_LIT("main"));']
sites = 1
cards = 0
while sites < SITES:
    k = cards % 5  # a few shared tag and class names, the rest unique text
    out.append('  cd_open(CD_LIT("section")); cd_class(CD_LIT("card card-%d"));' % k)
    out.append('  cd_open(CD_LIT("h2")); cd_text(CD_LIT(%s)); cd_close();' % c(text(sites)))
    out.append('  cd_open(CD_LIT("p")); cd_attr(CD_LIT("title"), CD_LIT(%s)); cd_text(CD_LIT(%s)); cd_close();' % (c(text(sites + 1)), c(text(sites + 2))))
    out.append('  cd_close();')
    sites += 8
    cards += 1
out += ['  cd_close();', '}']
open(sys.argv[2] if len(sys.argv) > 2 else 'apps/synth.c', 'w').write('\n'.join(out) + '\n')
